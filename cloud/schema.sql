CREATE TABLE IF NOT EXISTS temps (id INTEGER PRIMARY KEY AUTOINCREMENT, ts INTEGER NOT NULL, device_ts TEXT, seq INTEGER, temp_f REAL NOT NULL, target_f REAL);
CREATE INDEX IF NOT EXISTS idx_temps_ts ON temps(ts);
CREATE TABLE IF NOT EXISTS advice (id INTEGER PRIMARY KEY AUTOINCREMENT, ts INTEGER NOT NULL, advice TEXT NOT NULL, predicted_f REAL, minutes_left INTEGER, cannot_reach INTEGER);
CREATE INDEX IF NOT EXISTS idx_advice_ts ON advice(ts);
CREATE TABLE IF NOT EXISTS status (id INTEGER PRIMARY KEY AUTOINCREMENT, ts INTEGER NOT NULL, status TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS idx_status_ts ON status(ts);
